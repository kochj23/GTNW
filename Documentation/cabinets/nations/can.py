def rows(title, data, sources):
    out = []
    for r in data:
        name, frm, to = r[0], r[1], r[2]
        kw = dict(r[3]) if len(r) > 3 else {}
        t = kw.pop("title", title)
        s = kw.pop("sources", sources)
        out.append(H(name, t, frm, to, sources=s, native=kw.pop("native", ""), **kw))
    return out


