#!/usr/bin/env python3
"""Generate Shared/Engine/Shadow/ArsenalData.swift from gtnw_us_arsenal_by_era.json (3.6.0).

Run from anywhere:  python3 Documentation/arsenal/gen_swift.py
The JSON comes from build.py + data.py in this folder (encyclopedia-level research: names, dates, legal status,
example systems). Options first available after April 2026 are flagged low-confidence (background flavour only).
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "gtnw_us_arsenal_by_era.json")
OUT = os.path.join(HERE, "..", "..", "Shared", "Engine", "Shadow", "ArsenalData.swift")
LOW_CONFIDENCE_AFTER = 2026   # research dated after ~April 2026 is flavour, never the only gate


def q(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def opt(n):
    return "nil" if n is None else str(int(n))


def main():
    d = json.load(open(SRC))
    lines = [
        "//",
        "//  ArsenalData.swift",
        "//  Global Thermal Nuclear War",
        "//",
        "//  GENERATED by Documentation/arsenal/gen_swift.py from gtnw_us_arsenal_by_era.json. Do not edit by hand.",
        "//  U.S. offensive options by era, 1789-2030: names, dates, legal status and example systems (encyclopedia level).",
        "//",
        "",
        "import Foundation",
        "",
        "extension ArsenalCatalog {",
        "    static let options: [ArsenalOption] = [",
    ]
    for o in d["options"]:
        periods = ", ".join(
            f".init(from: {opt(p['from'])}, to: {opt(p['to'])}, status: .{ {'treaty_banned': 'treatyBanned'}.get(p['status'], p['status']) }, note: {q(p.get('note', ''))})"
            for p in o["legal_status_by_period"])
        ex = ", ".join(q(x) for x in o.get("example_systems", [])[:4])
        low = "true" if (o["available_from"] or 0) > LOW_CONFIDENCE_AFTER else "false"
        lines.append(f"        ArsenalOption(id: {q(o['id'])}, category: {q(o['category'])}, name: {q(o['name'])},")
        lines.append(f"                      from: {opt(o['available_from'])}, to: {opt(o['available_to'])}, lowConfidence: {low},")
        lines.append(f"                      periods: [{periods}],")
        lines.append(f"                      examples: [{ex}]),")
    lines += ["    ]", "}", ""]
    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {os.path.normpath(OUT)} ({len(d['options'])} options)")


if __name__ == "__main__":
    main()
