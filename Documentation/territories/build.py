#!/usr/bin/env python3
"""Validate data.py and generate Shared/Engine/Shadow/TerritoryData.swift (3.13.0).  Run: python3 build.py"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from data import ERAS, ACQUISITIONS

OUT = os.path.join(HERE, "..", "..", "Shared", "Engine", "Shadow", "TerritoryData.swift")


def q(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def check():
    by = {}
    for e in ERAS:
        land, a, b, kind, owner, name, extra = e
        assert kind in ("colony", "indigenous"), e
        assert a < b, e
        assert (kind == "colony") == bool(owner), e
        by.setdefault(land, []).append((a, b))
    for land, spans in by.items():
        spans.sort()
        for (a1, b1), (a2, b2) in zip(spans, spans[1:]):
            assert b1 <= a2, f"{land}: overlapping eras {spans}"
    for a in ACQUISITIONS:
        assert a[3] < a[4], a


def main():
    check()
    lines = ["//", "//  TerritoryData.swift", "//  Global Thermal Nuclear War", "//",
             "//  GENERATED by Documentation/territories/build.py from data.py. Do not edit by hand.",
             "//  Who held each modern country's land before it existed in the game (encyclopedia level; sources in data.py).",
             "//", "", "import Foundation", "", "extension PreStateModel {", "    static let eras: [PreStateEra] = ["]
    for land, a, b, kind, owner, name, extra in ERAS:
        lines.append(f"        PreStateEra(land: {q(land)}, from: {a}, to: {b}, kind: .{kind}, owner: {q(owner)}, name: {q(name)}, extra: {extra}),")
    lines += ["    ]", "", "    static let acquisitions: [HistoricalAcquisition] = ["]
    for key, name, owner, a, b, price, land, value in ACQUISITIONS:
        lines.append(f"        HistoricalAcquisition(id: {q(key)}, name: {q(name)}, owner: {q(owner)}, from: {a}, to: {b}, price: {q(price)}, land: {q(land)}, value: {value}),")
    lines += ["    ]", "}", ""]
    open(OUT, "w").write("\n".join(lines))
    print(f"wrote {os.path.normpath(OUT)}: {len(ERAS)} eras, {len(ACQUISITIONS)} acquisitions")


if __name__ == "__main__":
    main()
